"""WHO Child Growth Standards (2006): the reference table loader.

``nutrition-data/who-growth-standards.yaml`` is generated by
``scripts/build_growth_tables.py`` from WHO's published LMS tables and validated whole at
load time, like the food table: one malformed row fails the load with an error naming the
indicator, sex, and key, and no partial table is ever handed to callers — a missing
parameter would otherwise turn into a wrong percentile on a parent's screen.

No model call, no I/O beyond the committed file, and no LangChain import anywhere under
``backend.nutrition`` (Day 4 Decision 1).
"""

import datetime as dt
import logging
import math
import statistics
from collections.abc import Callable
from enum import StrEnum
from functools import lru_cache
from pathlib import Path

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from backend.chat.copy import GROWTH_HEIGHT_OUT_OF_RANGE, GROWTH_NEEDS_HEIGHT
from backend.models.enums import Sex
from backend.schemas.tools import (
    GrowthAssessmentInput,
    GrowthAssessmentResult,
    GrowthBand,
    GrowthCurve,
    GrowthCurveSet,
    GrowthIndicatorResult,
    LmsReference,
    SkippedIndicator,
)

logger = logging.getLogger(__name__)

DEFAULT_GROWTH_TABLE_PATH = Path("nutrition-data") / "who-growth-standards.yaml"


class GrowthIndicator(StrEnum):
    """The four WHO indicators the assessment covers."""

    WEIGHT_FOR_AGE = "weight_for_age"
    LENGTH_HEIGHT_FOR_AGE = "length_height_for_age"
    WEIGHT_FOR_LENGTH_HEIGHT = "weight_for_length_height"
    BMI_FOR_AGE = "bmi_for_age"


# The weight-for-length/height indicator has two WHO tables whose centimetre keys overlap
# (65-110 cm) with different values; age selects between them at assessment time.
_LENGTH_PART = "length"  # recumbent length, under 24 months (45.0-110.0 cm)
_HEIGHT_PART = "height"  # standing height, from 24 months (65.0-120.0 cm)

_MONTHLY_INDICATORS = (
    GrowthIndicator.WEIGHT_FOR_AGE,
    GrowthIndicator.LENGTH_HEIGHT_FOR_AGE,
    GrowthIndicator.BMI_FOR_AGE,
)

Rows = list[list[float]]


class GrowthSourceFile(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    name: str = Field(min_length=1)
    url: str = Field(min_length=1)
    sha256: str = Field(pattern=r"^[0-9a-f]{64}$")


class GrowthTable(BaseModel):
    """The whole reference file; every row is checked before any lookup is possible."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    version: int = Field(ge=1)
    source: str = Field(min_length=1)
    source_url: str = Field(min_length=1)
    retrieved: dt.date
    files: list[GrowthSourceFile] = Field(min_length=1)
    tables: dict[GrowthIndicator, dict[Sex, Rows | dict[str, Rows]]]

    @model_validator(mode="after")
    def _whole_table_is_sound(self) -> GrowthTable:
        for indicator in GrowthIndicator:
            by_sex = self.tables.get(indicator)
            if by_sex is None:
                raise ValueError(f"tables.{indicator}: indicator missing")
            for sex in Sex:
                entry = by_sex.get(sex)
                if entry is None:
                    raise ValueError(f"tables.{indicator}.{sex}: sex missing")
                if indicator is GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT:
                    if not isinstance(entry, dict) or set(entry) != {_LENGTH_PART, _HEIGHT_PART}:
                        raise ValueError(
                            f"tables.{indicator}.{sex}: expected exactly the "
                            f"'{_LENGTH_PART}' and '{_HEIGHT_PART}' subtables"
                        )
                    for part, rows in entry.items():
                        _check_rows(rows, f"{indicator}/{sex}/{part}", step=0.1)
                else:
                    if not isinstance(entry, list):
                        raise ValueError(f"tables.{indicator}.{sex}: expected a list of rows")
                    _check_rows(rows=entry, where=f"{indicator}/{sex}", step=1.0)
                    keys = [row[0] for row in entry]
                    if keys[0] != 0 or keys[-1] != 60:
                        raise ValueError(
                            f"tables.{indicator}/{sex}: months must cover 0-60, "
                            f"got {keys[0]}-{keys[-1]}"
                        )
        return self


def _check_rows(rows: Rows, where: str, step: float) -> None:
    """Finite L, M > 0, S > 0, contiguous keys — the error names indicator, sex, and key."""
    if not rows:
        raise ValueError(f"tables.{where}: table is empty")
    previous_key: float | None = None
    for row in rows:
        if not isinstance(row, list) or len(row) != 4:
            key = row[0] if isinstance(row, list) and row else "?"
            raise ValueError(f"tables.{where} key {key}: expected [key, L, M, S]")
        key, big_l, big_m, big_s = row
        if not all(isinstance(v, int | float) and math.isfinite(v) for v in row):
            raise ValueError(f"tables.{where} key {key}: L, M, S must be finite numbers")
        if big_m <= 0:
            raise ValueError(f"tables.{where} key {key}: M must be > 0")
        if big_s <= 0:
            raise ValueError(f"tables.{where} key {key}: S must be > 0")
        if previous_key is not None and round(key - previous_key, 6) != step:
            raise ValueError(
                f"tables.{where} key {key}: keys must be contiguous in steps of {step} "
                f"(previous key {previous_key})"
            )
        previous_key = key


class LoadedGrowthTable:
    """A validated table with keyed LMS lookup. Immutable after construction."""

    def __init__(self, table: GrowthTable) -> None:
        self.table = table
        self._monthly: dict[tuple[GrowthIndicator, Sex, int], tuple[float, float, float]] = {}
        for indicator in _MONTHLY_INDICATORS:
            for sex, rows in table.tables[indicator].items():
                assert isinstance(rows, list)
                for key, big_l, big_m, big_s in rows:
                    self._monthly[(indicator, sex, int(key))] = (big_l, big_m, big_s)
        self._by_cm: dict[tuple[Sex, str], dict[float, tuple[float, float, float]]] = {}
        for sex, parts in table.tables[GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT].items():
            assert isinstance(parts, dict)
            for part, rows in parts.items():
                self._by_cm[(sex, part)] = {
                    round(key, 1): (big_l, big_m, big_s) for key, big_l, big_m, big_s in rows
                }

    @property
    def source(self) -> str:
        return self.table.source

    @property
    def source_url(self) -> str:
        return self.table.source_url

    def monthly(
        self, indicator: GrowthIndicator, sex: Sex, age_months: int
    ) -> tuple[float, float, float]:
        """L, M, S for a monthly indicator; ages are pre-validated to the table's 0-60."""
        return self._monthly[(indicator, sex, age_months)]

    def weight_for_lh(
        self, sex: Sex, age_months: int, length_height_cm: float
    ) -> tuple[float, float, float] | None:
        """L, M, S from the length table under 24 months, the height table from 24.

        ``None`` when the measurement lies outside the covered range — the caller reports
        the indicator as skipped rather than failing.
        """
        part = _LENGTH_PART if age_months < 24 else _HEIGHT_PART
        return self._by_cm[(sex, part)].get(round(length_height_cm, 1))

    def weight_for_lh_range(self, sex: Sex, age_months: int) -> tuple[float, float]:
        """The covered centimetre range of the table ``weight_for_lh`` would use."""
        part = _LENGTH_PART if age_months < 24 else _HEIGHT_PART
        keys = self._by_cm[(sex, part)]
        return (min(keys), max(keys))

    def cm_rows(self, sex: Sex, use_height_table: bool) -> dict[float, tuple[float, float, float]]:
        """The whole length (under 24 months) or height (from 24) table, keyed by 0.1 cm."""
        return self._by_cm[(sex, _HEIGHT_PART if use_height_table else _LENGTH_PART)]


def load_growth_table(path: str | Path = DEFAULT_GROWTH_TABLE_PATH) -> LoadedGrowthTable:
    """Read and validate the whole table, or raise ``ValueError`` naming the problem."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Growth table not found: {path}")
    try:
        raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as exc:
        raise ValueError(f"Invalid {path}: {exc}") from exc
    try:
        table = GrowthTable.model_validate(raw)
    except ValidationError as exc:
        first = exc.errors()[0]
        raise ValueError(f"Invalid {path}: {first['msg']}") from exc
    logger.info("Loaded growth table %s: %s (retrieved %s)", path, table.source, table.retrieved)
    return LoadedGrowthTable(table)


@lru_cache(maxsize=1)
def get_growth_table() -> LoadedGrowthTable:
    """Process-wide table, loaded on first use from the committed file."""
    return load_growth_table(DEFAULT_GROWTH_TABLE_PATH)


def reset_growth_table_cache() -> None:
    """For tests that swap the table."""
    get_growth_table.cache_clear()
    get_reference_curves.cache_clear()


# -- assessment arithmetic (design Decisions 3-5) ---------------------------------------------
#
# WHO's published LMS method (their instructions-en.pdf): z = ((x/M)^L − 1) / (L·S), with a
# tail adjustment beyond ±3 SD for the weight-based indicators only. Pure arithmetic over
# the validated table; no model call anywhere near a number (hard rule 7).

# WHO's own classification terms, from the cut-off table in
# knowledge-base/who-child-growth-standards-2006.md — quoted, never invented, and absent
# ("—" in WHO's table) for weight-for-age and length/height-for-age above the range.
_WHO_LABELS: dict[tuple[GrowthIndicator, str], str] = {
    (GrowthIndicator.LENGTH_HEIGHT_FOR_AGE, "well_below"): "severely stunted",
    (GrowthIndicator.LENGTH_HEIGHT_FOR_AGE, "below"): "stunted",
    (GrowthIndicator.WEIGHT_FOR_AGE, "well_below"): "severely underweight",
    (GrowthIndicator.WEIGHT_FOR_AGE, "below"): "underweight",
    (GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT, "well_below"): "severely wasted",
    (GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT, "below"): "wasted",
    (GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT, "above"): "overweight",
    (GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT, "well_above"): "obese",
    (GrowthIndicator.BMI_FOR_AGE, "well_below"): "severely wasted",
    (GrowthIndicator.BMI_FOR_AGE, "below"): "wasted",
    (GrowthIndicator.BMI_FOR_AGE, "above"): "overweight",
    (GrowthIndicator.BMI_FOR_AGE, "well_above"): "obese",
}

# Weight-based indicators take WHO's tail adjustment; length/height-for-age does not.
_TAIL_ADJUSTED = frozenset(
    {
        GrowthIndicator.WEIGHT_FOR_AGE,
        GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT,
        GrowthIndicator.BMI_FOR_AGE,
    }
)

GROWTH_SOURCE = "WHO Child Growth Standards (2006)"


def _sd(t: float, big_l: float, big_m: float, big_s: float) -> float:
    """The measurement value sitting exactly at z = t for these LMS parameters."""
    if big_l == 0:
        return big_m * math.exp(big_s * t)
    return big_m * (1 + big_l * big_s * t) ** (1 / big_l)


def z_score(x: float, big_l: float, big_m: float, big_s: float, tail_adjust: bool) -> float:
    """WHO LMS z-score, with the ±3 SD tail adjustment where WHO applies one."""
    z = math.log(x / big_m) / big_s if big_l == 0 else ((x / big_m) ** big_l - 1) / (big_l * big_s)
    if tail_adjust and z > 3:
        sd3, sd2 = _sd(3, big_l, big_m, big_s), _sd(2, big_l, big_m, big_s)
        z = 3 + (x - sd3) / (sd3 - sd2)
    elif tail_adjust and z < -3:
        sd3neg, sd2neg = _sd(-3, big_l, big_m, big_s), _sd(-2, big_l, big_m, big_s)
        z = -3 + (x - sd3neg) / (sd2neg - sd3neg)
    return z


def percentile(z: float) -> float:
    return statistics.NormalDist().cdf(z) * 100


def reference(big_l: float, big_m: float, big_s: float) -> LmsReference:
    """WHO's −2 SD, median, and +2 SD, one decimal, as the published tables print them."""
    return LmsReference(
        sd2neg=round(_sd(-2, big_l, big_m, big_s), 1),
        median=round(big_m, 1),
        sd2pos=round(_sd(2, big_l, big_m, big_s), 1),
    )


# -- reference curves (growth-charts design Decision 1) ---------------------------------------
#
# The same LMS parameters read the other way: the value that sits at a given percentile.
# The 10th-90th percentiles lie within ±1.29 SD, so WHO's tail adjustment never applies.

CURVE_PERCENTILES: tuple[int, ...] = (10, 20, 30, 40, 50, 60, 70, 80, 90)

_CURVE_UNITS: dict[GrowthIndicator, str] = {
    GrowthIndicator.WEIGHT_FOR_AGE: "kg",
    GrowthIndicator.LENGTH_HEIGHT_FOR_AGE: "cm",
    GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT: "kg",
    GrowthIndicator.BMI_FOR_AGE: "kg/m²",
}


def value_at_percentile(p: float, big_l: float, big_m: float, big_s: float) -> float:
    """The measurement value at percentile ``p`` (0 < p < 100): the inverse of ``z_score``."""
    return _sd(statistics.NormalDist().inv_cdf(p / 100), big_l, big_m, big_s)


def _curve_set(
    indicator: GrowthIndicator,
    x_unit: str,
    x_label_table: str | None,
    xs: list[float],
    lms_at: Callable[[float], tuple[float, float, float]],
) -> GrowthCurveSet:
    decimals = 2 if indicator is GrowthIndicator.BMI_FOR_AGE else 1
    curves = [
        GrowthCurve(
            percentile=p,
            values=[round(value_at_percentile(p, *lms_at(x)), decimals) for x in xs],
        )
        for p in CURVE_PERCENTILES
    ]
    return GrowthCurveSet(
        indicator=indicator.value,
        x_unit=x_unit,  # type: ignore[arg-type]  # the two literals are the only callers
        x_label_table=x_label_table,  # type: ignore[arg-type]
        y_unit=_CURVE_UNITS[indicator],
        xs=xs,
        curves=curves,
    )


def reference_curves(
    table: LoadedGrowthTable, sex: Sex, use_height_table: bool
) -> list[GrowthCurveSet]:
    """The 10th-90th percentile curves for one sex: monthly indicators over months 0-60,
    weight-for-length/height at every whole centimetre of the chosen table."""
    months = [float(month) for month in range(0, 61)]
    sets = [
        _curve_set(
            indicator,
            "months",
            None,
            months,
            lambda x, indicator=indicator: table.monthly(indicator, sex, int(x)),
        )
        for indicator in (GrowthIndicator.WEIGHT_FOR_AGE, GrowthIndicator.LENGTH_HEIGHT_FOR_AGE)
    ]
    rows = table.cm_rows(sex, use_height_table)
    lo, hi = int(min(rows)), int(max(rows))
    centimetres = [float(cm) for cm in range(lo, hi + 1)]
    sets.append(
        _curve_set(
            GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT,
            "cm",
            _HEIGHT_PART if use_height_table else _LENGTH_PART,
            centimetres,
            lambda x: rows[round(x, 1)],
        )
    )
    sets.append(
        _curve_set(
            GrowthIndicator.BMI_FOR_AGE,
            "months",
            None,
            months,
            lambda x: table.monthly(GrowthIndicator.BMI_FOR_AGE, sex, int(x)),
        )
    )
    return sets


@lru_cache(maxsize=4)
def get_reference_curves(sex: Sex, use_height_table: bool) -> tuple[GrowthCurveSet, ...]:
    """Process-wide curves from the committed table; one entry per (sex, table)."""
    return tuple(reference_curves(get_growth_table(), sex, use_height_table))


def band_for(indicator: GrowthIndicator, z: float) -> GrowthBand:
    """WHO cut-offs: a band changes strictly beyond −3, −2, +2, +3 ('below −3' is severe)."""
    del indicator  # same cut-offs for all four; kept in the signature for call-site clarity
    if z < -3:
        return "well_below"
    if z < -2:
        return "below"
    if z <= 2:
        return "expected"
    if z <= 3:
        return "above"
    return "well_above"


def who_label_for(indicator: GrowthIndicator, band: GrowthBand) -> str | None:
    return _WHO_LABELS.get((indicator, band))


def _indicator_result(
    indicator: GrowthIndicator,
    measurement: float,
    unit: str,
    lms: tuple[float, float, float],
) -> GrowthIndicatorResult:
    big_l, big_m, big_s = lms
    z = z_score(measurement, big_l, big_m, big_s, tail_adjust=indicator in _TAIL_ADJUSTED)
    band = band_for(indicator, z)
    return GrowthIndicatorResult(
        indicator=indicator.value,
        measurement=round(measurement, 2),
        unit=unit,
        z_score=round(z, 2),
        percentile=round(percentile(z), 1),
        band=band,
        who_label=who_label_for(indicator, band),
        reference=reference(big_l, big_m, big_s),
    )


def assess_growth(
    params: GrowthAssessmentInput, table: LoadedGrowthTable
) -> GrowthAssessmentResult:
    """Place the child on each WHO indicator the inputs allow; skip the rest, never fail."""
    age, sex, weight, height = params.age_months, params.sex, params.weight_kg, params.height_cm
    reading = "recumbent length" if age < 24 else "standing height"
    indicators = [
        _indicator_result(
            GrowthIndicator.WEIGHT_FOR_AGE,
            weight,
            "kg",
            table.monthly(GrowthIndicator.WEIGHT_FOR_AGE, sex, age),
        )
    ]
    skipped = []

    if height is None:
        skipped = [
            SkippedIndicator(indicator=indicator.value, reason=GROWTH_NEEDS_HEIGHT)
            for indicator in (
                GrowthIndicator.LENGTH_HEIGHT_FOR_AGE,
                GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT,
                GrowthIndicator.BMI_FOR_AGE,
            )
        ]
    else:
        indicators.append(
            _indicator_result(
                GrowthIndicator.LENGTH_HEIGHT_FOR_AGE,
                height,
                "cm",
                table.monthly(GrowthIndicator.LENGTH_HEIGHT_FOR_AGE, sex, age),
            )
        )
        lms = table.weight_for_lh(sex, age, height)
        if lms is None:
            lo, hi = table.weight_for_lh_range(sex, age)
            skipped.append(
                SkippedIndicator(
                    indicator=GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT.value,
                    reason=GROWTH_HEIGHT_OUT_OF_RANGE(lo, hi),
                )
            )
        else:
            indicators.append(
                _indicator_result(GrowthIndicator.WEIGHT_FOR_LENGTH_HEIGHT, weight, "kg", lms)
            )
        bmi = weight / (height / 100) ** 2
        indicators.append(
            _indicator_result(
                GrowthIndicator.BMI_FOR_AGE,
                bmi,
                "kg/m²",
                table.monthly(GrowthIndicator.BMI_FOR_AGE, sex, age),
            )
        )

    return GrowthAssessmentResult(
        age_months=age,
        sex=sex,
        weight_kg=weight,
        height_cm=height,
        indicators=indicators,
        skipped=skipped,
        source=GROWTH_SOURCE,
        source_url=table.source_url,
        note=(
            f"Compared by completed month (month {age}) on WHO's monthly tables; the "
            f"height field is read as {reading} at this age."
        ),
    )

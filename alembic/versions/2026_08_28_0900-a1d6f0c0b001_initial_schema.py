"""Initial schema: five controlled-vocabulary enum types, users, child profiles, feedings.

Revision ID: a1d6f0c0b001
Revises:
Create Date: 2026-08-28 09:00:00

Hand-written rather than autogenerated so the enum-type lifecycle is explicit. Alembic's
autogenerate creates PostgreSQL enum types as a side effect of ``create_table`` but does
not drop them in ``downgrade()``, which leaves a second ``upgrade`` failing with
"type already exists". Here every type is created before the tables that use it and
dropped after them, so ``downgrade base`` followed by ``upgrade head`` round-trips.

Adding a member to one of these vocabularies later is ``ALTER TYPE ... ADD VALUE``.
Before PostgreSQL 12 that statement could not run inside a transaction block; from 12 it
can, but the new value cannot be *used* in the same transaction it was added in. A future
migration that adds a value and then backfills rows with it must therefore either run the
backfill in a separate migration or use ``op.get_context().autocommit_block()``.
"""

